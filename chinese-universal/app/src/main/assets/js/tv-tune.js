/* ===================== 电视显示调参（★ 可热更，不用出新 APK） =====================
 * 用途：机顶盒/电视上出现「显示比例异常」时（整体偏大偏小、被 overscan 裁边、
 *       分辨率档位判错），只改这个文件重新出热更包就能修好，用户不用重装 APK。
 *
 * 使用纪律：
 *   1. 只调整数值，不要在这里写逻辑 —— 逻辑在 js/tv.js，那边有兜底。
 *   2. 每一项 tv.js 都做了「取不到就用内置默认值」的兜底：本文件缺失、字段写错、
 *      热更包没下发，都只是退回默认显示，不会白屏。
 *   3. 改完必须：node tools/gen-pack.mjs → 推 gh-pages → 设备打开两次生效。
 *
 * 调参顺序建议：整体不对先动 scaleK；只有某一档不对动 tiers；单个盒子特例动 forceScale。
 */
(function () {
  window.TV_TUNE = {
    /* ★ 2026-09-21 新增：触屏「电视一体机」上原生桥 isTV() 会误报 false
       （系统非 TV 模式、无 LEANBACK、但有触屏，三重判定全落空），
       导致 body 被打成 phone、css/tv.css 整块失效、大屏上跑手机布局。
       tv.js 里加了「大屏 + 横屏 + 16:9」几何复核来兜底；置 false 可关掉它。 */
    tvForce: true,
    /* 电视 WebView 普遍把 CSS 视口报成物理分辨率的一半（1080p 报 960×540）。
       置 false 则直接用 CSS px 分档（个别虚报 dpr 的盒子可试）。 */
    dprFix: true,

    /* 分辨率分档：[物理宽度阈值, 物理高度阈值, 缩放系数]，从上往下第一个命中即生效。
       宽或高任意一个超过阈值就算命中（竖屏投屏等场景靠高度兜住）。 */
    tiers: [
      [3000, 1700, 2.2],   // 4K
      [2300, 1300, 1.8],   // 2K
      [1700,  950, 1.5],   // 1080p
      [1100,  620, 1.25]   // 720p
    ],

    base: 1.2,       // 一档都没命中时的兜底缩放
    scaleK: 1,       // 整体微调：1.1 = 整体放大 10%，0.9 = 缩小 10%（比例异常第一刀）
    forceScale: 0,   // 强制指定缩放（>0 时忽略分档与 scaleK，用于个别奇葩盒子）
    minScale: 0.7,   // 缩放上下限，防手滑填错导致 UI 撑爆或缩成蚂蚁
    maxScale: 3,

    /* 「必须一屏放下」的两个尺寸：取 min(基准 × 缩放, 视口高 × 比例)。
       不能用 CSS 的 min() —— 安卓 8 的 WebView 会整条声明丢掉，田字格会塌。 */
    tianK: 340, tianMaxVh: 0.42,   // 田字格边长
    picK: 260,  picMaxVh: 0.34     // 主视觉图边长
  };
})();
